public class DataTypes {
    public static void main(String[] args) {
        int num = 10;
        float f = 12.5f;
        double d = 25.75;
        char ch = 'A';
        boolean flag = true;

        System.out.println(num);
        System.out.println(f);
        System.out.println(d);
        System.out.println(ch);
        System.out.println(flag);
    }
}