public class TypeCasting {
    public static void main(String[] args) {

        double d = 12.99;
        int num = (int) d;

        int x = 50;
        double y = (double) x;

        System.out.println("Double: " + d);
        System.out.println("Int: " + num);

        System.out.println("Integer: " + x);
        System.out.println("Double: " + y);
    }
}